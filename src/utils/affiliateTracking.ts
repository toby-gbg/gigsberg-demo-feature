const UTM_PARAMS = ['utm_source', 'utm_medium'];

const isHostMatch = (hostname: string, hosts: string[]) =>
    hosts.some((host) => hostname === host || hostname.endsWith(`.${host}`));

export const isSearchResultReferer = (referer?: string, url?: string): boolean => {
    if (!referer || !url) return false;

    try {
        const constructedUrl = new URL(url);
        // If the referrer URL contains UTM parameters, treat it as non-organic
        if (UTM_PARAMS.some((param) => constructedUrl.searchParams.has(param))) {
            return false;
        }

        const referrerUrl = new URL(referer);
        const hostname = referrerUrl.hostname.toLowerCase();

        return isHostMatch(hostname, SEARCH_ENGINE_HOSTS);
    } catch {
        return false;
    }
};
